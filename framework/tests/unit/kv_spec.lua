local h = require("tests.lib.harness")
local kv = require("lib.kv")

h.describe("kv", function()
  h.it("parses simple pairs", function()
    local t, err = kv.parse("A=1\nB=two\n")
    h.ok(t, err)
    h.eq(t.A, "1")
    h.eq(t.B, "two")
  end)

  h.it("skips comments and blanks", function()
    local t, err = kv.parse("# comment\n\nA=1\n")
    h.ok(t, err)
    h.eq(t.A, "1")
  end)

  h.it("allows empty values", function()
    local t, err = kv.parse("A=\n")
    h.ok(t, err)
    h.eq(t.A, "")
  end)

  h.it("rejects duplicates", function()
    local t, err = kv.parse("A=1\nA=2\n")
    h.eq(t, nil)
    h.ok(err:match("duplicate key A"))
  end)

  h.it("rejects CR", function()
    local t, err = kv.parse("A=1\r\n")
    h.eq(t, nil)
    h.ok(err:match("CR is not allowed"))
  end)

  h.it("rejects malformed lines", function()
    local t, err = kv.parse("A\n")
    h.eq(t, nil)
    h.ok(err:match("expected KEY=VALUE"))
  end)
end)
