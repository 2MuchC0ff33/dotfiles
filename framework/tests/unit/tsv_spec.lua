local h = require("tests.lib.harness")
local tsv = require("lib.tsv")

h.describe("tsv", function()
  h.it("parses rows", function()
    local rows, err = tsv.parse("a\tb\tc\n1\t2\t3\n", 3)
    h.ok(rows, err)
    h.eq(#rows, 2)
    h.eq(rows[2][3], "3")
  end)

  h.it("preserves empty trailing fields", function()
    local rows, err = tsv.parse("a\tb\t\n", 3)
    h.ok(rows, err)
    h.eq(#rows[1], 3)
    h.eq(rows[1][3], "")
  end)

  h.it("rejects a field-count mismatch", function()
    local rows, err = tsv.parse("a\tb\n", 3)
    h.eq(rows, nil)
    h.ok(err:match("expected 3 fields, found 2"))
  end)

  h.it("rejects CR", function()
    local rows, err = tsv.parse("a\tb\r\n", 2)
    h.eq(rows, nil)
    h.ok(err:match("CR/NUL is not allowed"))
  end)

  h.it("skips blank lines", function()
    local rows, err = tsv.parse("\na\tb\n\n", 2)
    h.ok(rows, err)
    h.eq(#rows, 1)
  end)
end)
