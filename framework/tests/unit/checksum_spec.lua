local h = require("tests.lib.harness")
local checksum = require("lib.checksum")

h.describe("checksum", function()
  h.it("parses a cksum line", function()
    local crc, size, path = checksum.parse_line("123 45 etc/x")
    h.eq(crc, "123")
    h.eq(size, "45")
    h.eq(path, "etc/x")
  end)

  h.it("rejects absolute paths", function()
    local crc, _, _, err = checksum.parse_line("123 45 /etc/passwd")
    h.eq(crc, nil)
    h.ok(err:match("absolute"))
  end)

  h.it("rejects parent traversal", function()
    local crc, _, _, err = checksum.parse_line("123 45 ../x")
    h.eq(crc, nil)
    h.ok(err:match("parent traversal"))
  end)

  h.it("rejects control characters", function()
    local crc, _, _, err = checksum.parse_line("123 45 a\nb")
    h.eq(crc, nil)
    h.ok(err:match("control characters"))
  end)

  h.it("formats and matches", function()
    local line = checksum.format_line("123 45 etc/x")
    h.eq(line, "123 45 etc/x")
    local entry = { crc = "123", size = "45", path = "etc/x" }
    h.ok(checksum.matches(entry, "123 45 etc/x"))
    local ok, err = checksum.matches(entry, "124 45 etc/x")
    h.eq(ok, false)
    h.ok(err:match("mismatch"))
  end)

  h.it("reads a manifest", function()
    local path = "work/checksum.spec.cksum"
    local f = assert(io.open(path, "w"))
    f:write("# comment\n123 45 etc/x\n")
    f:close()
    local entries, err = checksum.read_manifest(path)
    h.ok(entries, err)
    h.eq(#entries, 1)
    h.eq(entries[1].path, "etc/x")
    os.remove(path)
  end)
end)
